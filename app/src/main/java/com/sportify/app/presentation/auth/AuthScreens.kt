@Composable
private fun AuthLayout(title: String, subtitle: String, content: @Composable ColumnScope.() -> Unit) {
    Column(
        Modifier.fillMaxSize().systemBarsPadding().imePadding()
            .verticalScroll(rememberScrollState()).padding(24.dp),
        horizontalAlignment = Alignment.CenterHorizontally, verticalArrangement = Arrangement.Center
    ) {
        Icon(Icons.Default.SportsTennis, null, Modifier.size(64.dp), tint = MaterialTheme.colorScheme.primary)
        Spacer(Modifier.height(8.dp))
        Text(title, style = MaterialTheme.typography.headlineMedium, fontWeight = FontWeight.Bold)
        Text(subtitle, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
        Spacer(Modifier.height(24.dp))
        content()
    }
}

@Composable
fun LoginScreen(onRegister: () -> Unit, vm: AuthViewModel = hiltViewModel()) {
    val ui by vm.ui.collectAsStateWithLifecycle()
    var email by remember { mutableStateOf("") }
    var pw by remember { mutableStateOf("") }
    val context = LocalContext.current

    val googleLauncher = rememberLauncherForActivityResult(ActivityResultContracts.StartActivityForResult()) { res ->
        try {
            val acc = GoogleSignIn.getSignedInAccountFromIntent(res.data).getResult(ApiException::class.java)
            acc.idToken?.let(vm::google) ?: vm.setError("Google sign-in returned no token")
        } catch (e: ApiException) {
            if (e.statusCode != 12501) vm.setError("Google sign-in failed (${e.statusCode})") // 12501 = user cancelled
        }
    }

    AuthLayout("Welcome to Sportify", "Book courts and pitches in seconds") {
        OutlinedTextField(email, { email = it }, label = { Text("Email") }, singleLine = true,
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email), modifier = Modifier.fillMaxWidth())
        Spacer(Modifier.height(12.dp))
        OutlinedTextField(pw, { pw = it }, label = { Text("Password") }, singleLine = true,
            visualTransformation = PasswordVisualTransformation(),
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password), modifier = Modifier.fillMaxWidth())
        TextButton(onClick = { vm.resetPassword(email) }, modifier = Modifier.align(Alignment.End)) { Text("Forgot password?") }
        ErrorText(ui.error)
        ui.info?.let { Text(it, color = MaterialTheme.colorScheme.primary) }
        Button(onClick = { vm.signIn(email, pw) }, enabled = !ui.loading, modifier = Modifier.fillMaxWidth().height(52.dp)) {
            if (ui.loading) CircularProgressIndicator(Modifier.size(22.dp), strokeWidth = 2.dp) else Text("Sign in")
        }
        Spacer(Modifier.height(12.dp))
        OutlinedButton(
            onClick = {
                val gso = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
                    .requestIdToken(context.getString(R.string.default_web_client_id)) // generated by google-services plugin
                    .requestEmail().build()
                val client = GoogleSignIn.getClient(context, gso)
                client.signOut().addOnCompleteListener { googleLauncher.launch(client.signInIntent) } // forces account chooser
            },
            enabled = !ui.loading, modifier = Modifier.fillMaxWidth().height(52.dp)
        ) { Text("Continue with Google") }
        TextButton(onClick = onRegister) { Text("New here? Create an account") }
    }
}

@Composable
fun RegisterScreen(onBack: () -> Unit, vm: AuthViewModel = hiltViewModel()) {
    val ui by vm.ui.collectAsStateWithLifecycle()
    var name by remember { mutableStateOf("") }
    var email by remember { mutableStateOf("") }
    var pw by remember { mutableStateOf("") }

    AuthLayout("Create account", "Join Sportify and start playing") {
        OutlinedTextField(name, { name = it }, label = { Text("Full name") }, singleLine = true, modifier = Modifier.fillMaxWidth())
        Spacer(Modifier.height(12.dp))
        OutlinedTextField(email, { email = it }, label = { Text("Email") }, singleLine = true,
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email), modifier = Modifier.fillMaxWidth())
        Spacer(Modifier.height(12.dp))
        OutlinedTextField(pw, { pw = it }, label = { Text("Password (min 6 chars)") }, singleLine = true,
            visualTransformation = PasswordVisualTransformation(),
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password), modifier = Modifier.fillMaxWidth())
        Spacer(Modifier.height(8.dp))
        ErrorText(ui.error)
        Button(onClick = { vm.signUp(name, email, pw) }, enabled = !ui.loading, modifier = Modifier.fillMaxWidth().height(52.dp)) {
            if (ui.loading) CircularProgressIndicator(Modifier.size(22.dp), strokeWidth = 2.dp) else Text("Sign up")
        }
        TextButton(onClick = onBack) { Text("Already have an account? Sign in") }
    }
}
